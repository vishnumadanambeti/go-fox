const STORAGE_KEY = 'gofox:locale'

export function getSavedLocale(): LocaleCode {
  try {
    const raw = localStorage.getItem(STORAGE_KEY) as LocaleCode
    if (raw && TRANSLATIONS[raw]) return raw
  } catch {
    /* storage blocked */
  }
  return 'en'
}

export function saveLocale(code: LocaleCode): void {
  try {
    localStorage.setItem(STORAGE_KEY, code)
    applyLocaleToDom(code)
  } catch {
    /* ignore */
  }
}

export function applyLocaleToDom(code: LocaleCode): void {
  if (typeof document === 'undefined') return
  const lang = LANGUAGES.find((l) => l.code === code) ?? LANGUAGES[0]
  document.documentElement.lang = code
  document.documentElement.dir = lang.dir
}

export function translate(key: string, locale: LocaleCode = getSavedLocale(), fallback?: string): string {
  const dict = TRANSLATIONS[locale] ?? TRANSLATIONS.en
  if (dict[key]) return dict[key]
  if (TRANSLATIONS.en[key]) return TRANSLATIONS.en[key]
  return fallback ?? key
}
